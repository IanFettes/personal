#include <iostream>
using namespace std;

int main () {
    int num1, num2, sum;

    // Read in 2 numbers from the user
    cout << "Enter 2 numbers:\n";
    cin >> num1 >> num2;

    // Add the numbers together
    sum = num1 + num2;

    // Display the sum
    cout << "Sum: " << sum << endl;
    return 0;
}